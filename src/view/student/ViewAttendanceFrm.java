    private void customizeUI() {

        lblStudentName.setText(currentUser.getFullName());

        tableModel = new DefaultTableModel(
                new Object[]{
                    "STT",
                    "Ngày",
                    "Môn học",
                    "Trạng thái",
                    "Ghi chú"
                },
                0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tblAttendance.setModel(tableModel);

        tblAttendance.setRowHeight(28);
        tblAttendance.getTableHeader().setReorderingAllowed(false);
    }

    private void loadAttendance() {

        tableModel.setRowCount(0);

        StudentProfile student
                = studentDAO.getByUserId(currentUser.getId());

        if (student == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Không tìm thấy hồ sơ học sinh!",
                    "Thông báo",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        List<Object[]> attendanceList
                = attendanceDAO.getByStudent(student.getId());

        int stt = 1;

        for (Object[] row : attendanceList) {

            tableModel.addRow(new Object[]{
                stt++,
                row[0], // Ngày
                row[1], // Môn học
                row[2], // Trạng thái
                row[3] // Ghi chú
            });
        }

        if (attendanceList.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Bạn chưa có dữ liệu điểm danh.",
                    "Thông báo",
                    JOptionPane.INFORMATION_MESSAGE
            );
        }
    }

