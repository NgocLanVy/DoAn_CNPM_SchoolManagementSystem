    private void customizeUI() {
        if (currentUser == null) {
            JOptionPane.showMessageDialog(this, "Không tìm thấy thông tin học sinh!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            this.dispose();
            new LoginFrm().setVisible(true);
            return;
        }
        // Hiển thị tên học sinh
        lblStudentName.setText(currentUser.getFullName());
        // Tạo model cho bảng
        tableModel = new DefaultTableModel(
                new Object[]{"STT", "Môn học", "Loại điểm", "Điểm", "Học kỳ"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblGrades.setModel(tableModel);
    }

    private void loadGrades() {
        tableModel.setRowCount(0);
        // Lấy hồ sơ học sinh từ tài khoản đang đăng nhập
        StudentProfile student = studentDAO.getByUserId(currentUser.getId());
        if (student == null) {
            JOptionPane.showMessageDialog(this, "Không tìm thấy hồ sơ học sinh!", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Lấy điểm của học sinh đó
        List<Grade> grades = gradeDAO.getByStudent(student.getId());
        int stt = 1;
        for (Grade g : grades) {
            tableModel.addRow(new Object[]{
                stt++,
                g.getSubjectName(),
                g.getExamType(),
                g.getScore(),
                g.getSemester()
            });
        }
        if (grades.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Bạn chưa có điểm.", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
        }
    }

