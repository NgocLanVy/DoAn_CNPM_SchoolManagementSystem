    private void loadTable() {
        tableModel.setRowCount(0);
        for (Subject s : subjectDAO.getAll()) {
            tableModel.addRow(new Object[]{s.getId(), s.getSubjectName(), s.getSubjectCode(), s.getDescription()});
        }
    }

    private void onRowSelected() {
        int row = tblSubjects.getSelectedRow();
        if (row < 0) {
            return;
        }
        selectedId = (int) tableModel.getValueAt(row, 0);
        txtSubjectName.setText((String) tableModel.getValueAt(row, 1));
        txtSubjectCode.setText((String) tableModel.getValueAt(row, 2));
        Object description = tableModel.getValueAt(row, 3);
        txtDescription.setText(description == null ? "" : description.toString());
    }
