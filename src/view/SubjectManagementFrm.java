    private void customizeUI() {
        tableModel = new DefaultTableModel(new Object[]{"ID", "Tên môn", "Mã môn", "Mô tả"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblSubjects.setModel(tableModel);
        tblSubjects.getSelectionModel().addListSelectionListener(e -> onRowSelected());
    }

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        Subject s = new Subject();
        s.setSubjectName(txtSubjectName.getText().trim());
        s.setSubjectCode(txtSubjectCode.getText().trim());
        s.setDescription(txtDescription.getText().trim());
        if (s.getSubjectName().isEmpty() || s.getSubjectCode().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Tên môn và Mã môn!");
            return;
        }
        if (subjectDAO.insert(s)) {
            JOptionPane.showMessageDialog(this, "Thêm môn học thành công!");
            loadTable();
            btnClearActionPerformed(null);
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! (Mã môn có thể đã tồn tại)");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (selectedId < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 môn học trong bảng!");
            return;
        }
        Subject s = new Subject();
        s.setId(selectedId);
        s.setSubjectName(txtSubjectName.getText().trim());
        s.setSubjectCode(txtSubjectCode.getText().trim());
        s.setDescription(txtDescription.getText().trim());
        if (subjectDAO.update(s)) {
            JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
            loadTable();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedId < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 môn học trong bảng!");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "Xóa môn học này?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            subjectDAO.delete(selectedId);
            loadTable();
            btnClearActionPerformed(null);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnClearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnClearActionPerformed
        // TODO add your handling code here:
        selectedId = -1;
        txtSubjectName.setText("");
        txtSubjectCode.setText("");
        txtDescription.setText("");
        tblSubjects.clearSelection();
    }//GEN-LAST:event_btnClearActionPerformed

