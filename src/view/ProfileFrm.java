    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        if (currentUser == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Không tìm thấy thông tin người dùng!",
                    "Lỗi",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        // Lấy dữ liệu từ form
        String fullName = txtFullName.getText().trim();
        String address = txtAddress.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();

        String gender = "";

        if (cboGender.getSelectedItem() != null) {
            gender = cboGender.getSelectedItem().toString();
        }

        // Kiểm tra họ tên
        if (fullName.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng nhập họ và tên!",
                    "Thông báo",
                    JOptionPane.WARNING_MESSAGE
            );

            txtFullName.requestFocus();
            return;
        }

        // Cập nhật dữ liệu vào User
        currentUser.setFullName(fullName);
        currentUser.setAddress(address);
        currentUser.setGender(gender);
        currentUser.setEmail(email);
        currentUser.setPhone(phone);

        // Lưu thông tin cá nhân
        boolean profileUpdated = userDAO.updateProfile(currentUser);

        if (!profileUpdated) {

            JOptionPane.showMessageDialog(
                    this,
                    "Cập nhật thông tin thất bại!",
                    "Lỗi",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        // Lấy mật khẩu mới
        String newPassword = new String(txtNewPassword.getPassword()).trim();

        // Nếu người dùng nhập mật khẩu mới
        if (!newPassword.isEmpty()) {

            boolean passwordUpdated
                    = userDAO.updatePassword(
                            currentUser.getId(),
                            newPassword
                    );

            if (!passwordUpdated) {

                JOptionPane.showMessageDialog(
                        this,
                        "Thông tin cá nhân đã lưu nhưng đổi mật khẩu thất bại!",
                        "Thông báo",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            // Cập nhật mật khẩu trong object hiện tại
            currentUser.setPasswordHash(newPassword);
        }

        // Cập nhật Session
        Session.setCurrentUser(currentUser);

        // Xóa ô mật khẩu
        txtNewPassword.setText("");

        JOptionPane.showMessageDialog(
                this,
                "Cập nhật thông tin thành công!",
                "Thông báo",
                JOptionPane.INFORMATION_MESSAGE
        );
    }//GEN-LAST:event_btnSaveActionPerformed

