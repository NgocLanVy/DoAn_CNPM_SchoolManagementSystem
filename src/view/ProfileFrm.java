    private void loadUserInfo() {

        if (currentUser == null) {
            return;
        }

        txtUsername.setText(currentUser.getUsername());

        txtRole.setText(getRoleName(currentUser.getRoleId()));

        txtFullName.setText(currentUser.getFullName());

        txtAddress.setText(currentUser.getAddress());

        txtEmail.setText(currentUser.getEmail());

        txtPhone.setText(currentUser.getPhone());

        // Xóa các item cũ
        cboGender.removeAllItems();

        // Thêm giới tính
        cboGender.addItem("Nam");
        cboGender.addItem("Nữ");
        cboGender.addItem("Khác");

        // Chọn giới tính hiện tại
        if (currentUser.getGender() != null) {
            cboGender.setSelectedItem(currentUser.getGender());
        }

        // Mật khẩu mới để trống
        txtNewPassword.setText("");
    }

    /**
     * Đổi RoleId thành tên Role
     */
    private String getRoleName(int roleId) {

        switch (roleId) {

            case 1:
                return "Admin";

            case 2:
                return "Giáo viên";

            case 3:
                return "Học sinh";

            case 4:
                return "Phụ huynh";

            default:
                return "Không xác định";
        }
    }
