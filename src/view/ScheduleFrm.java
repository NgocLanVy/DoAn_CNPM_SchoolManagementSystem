    private void addSchedule() {
        SchoolClass selectedClass = (SchoolClass) cboClass.getSelectedItem();
        Subject selectedSubject = (Subject) cboSubject.getSelectedItem();
        TeacherProfile selectedTeacher = (TeacherProfile) cboTeacher.getSelectedItem();
        if (currentUser.getRoleId() != 1) {
            JOptionPane.showMessageDialog(this, "Bạn không có quyền thêm thời khóa biểu!");
            return;
        }
        if (selectedClass == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn lớp!");
            return;
        }
        if (selectedSubject == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn môn học!");
            return;
        }

        if (selectedTeacher == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn giáo viên!");
            return;
        }
        if (txtStartTime.getText().trim().isEmpty() || txtEndTime.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập giờ bắt đầu và giờ kết thúc!");
            return;
        }

        try {
            Time startTime = Time.valueOf(txtStartTime.getText().trim() + ":00");
            Time endTime = Time.valueOf(txtEndTime.getText().trim() + ":00");
            if (!startTime.before(endTime)) {
                JOptionPane.showMessageDialog(this, "Giờ bắt đầu phải nhỏ hơn giờ kết thúc!");
                return;
            }
            Schedule s = new Schedule();
            s.setSchoolClassId(selectedClass.getId());
            s.setSubjectId(selectedSubject.getId());
            s.setTeacherId(selectedTeacher.getId());
            s.setDayOfWeek(cboDay.getSelectedIndex());
            s.setStartTime(startTime);
            s.setEndTime(endTime);
            s.setRoom(txtRoom.getText().trim());
            if (scheduleDAO.insert(s)) {
                JOptionPane.showMessageDialog(this, "Thêm thời khóa biểu thành công!");
                loadTable();
                clearForm();
            } else {
                JOptionPane.showMessageDialog(this, "Thêm thời khóa biểu thất bại!");
            }
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Giờ phải nhập dạng HH:mm\nVí dụ: 07:00");
        }
    }

    private void deleteSchedule() {
        if (currentUser.getRoleId() != 1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Bạn không có quyền xóa thời khóa biểu!"
            );
            return;
        }
        if (selectedId == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn thời khóa biểu cần xóa!"
            );

            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Bạn có chắc muốn xóa thời khóa biểu này?",
                "Xác nhận",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        if (scheduleDAO.delete(selectedId)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Xóa thành công!"
            );

            loadTable();

            clearForm();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Xóa thất bại!"
            );
        }
    }

