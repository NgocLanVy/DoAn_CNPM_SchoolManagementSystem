    private void onRowSelected() {

        int row = tblSchedule.getSelectedRow();

        if (row < 0) {
            return;
        }

        selectedId = Integer.parseInt(
                tableModel.getValueAt(row, 0).toString()
        );

        String className
                = tableModel.getValueAt(row, 1).toString();

        String subjectName
                = tableModel.getValueAt(row, 2).toString();

        String teacherName
                = tableModel.getValueAt(row, 3).toString();

        String dayName
                = tableModel.getValueAt(row, 4).toString();

        Object start
                = tableModel.getValueAt(row, 5);

        Object end
                = tableModel.getValueAt(row, 6);

        Object room
                = tableModel.getValueAt(row, 7);

        // Lớp
        for (int i = 0; i < cboClass.getItemCount(); i++) {

            SchoolClass c
                    = (SchoolClass) cboClass.getItemAt(i);

            if (c.toString().equals(className)) {

                cboClass.setSelectedIndex(i);

                break;
            }
        }

        // Môn học
        for (int i = 0; i < cboSubject.getItemCount(); i++) {

            Subject s
                    = (Subject) cboSubject.getItemAt(i);

            if (s.toString().equals(subjectName)) {

                cboSubject.setSelectedIndex(i);

                break;
            }
        }

        // Giáo viên
        for (int i = 0; i < cboTeacher.getItemCount(); i++) {

            TeacherProfile t
                    = (TeacherProfile) cboTeacher.getItemAt(i);

            if (t.getFullName().equals(teacherName)) {

                cboTeacher.setSelectedIndex(i);

                break;
            }
        }

        // Thứ
        for (int i = 0; i < ScheduleDAO.DAY_NAMES.length; i++) {

            if (ScheduleDAO.DAY_NAMES[i].equals(dayName)) {

                cboDay.setSelectedIndex(i);

                break;
            }
        }

        if (start != null) {

            String value = start.toString();

            txtStartTime.setText(
                    value.length() >= 5
                    ? value.substring(0, 5)
                    : value
            );
        }

        if (end != null) {

            String value = end.toString();

            txtEndTime.setText(
                    value.length() >= 5
                    ? value.substring(0, 5)
                    : value
            );
        }

        txtRoom.setText(
                room == null
                        ? ""
                        : room.toString()
        );
    }

    private void clearForm() {

        if (currentUser.getRoleId() != 1) {
            return;
        }

        selectedId = -1;

        if (cboClass.getItemCount() > 0) {
            cboClass.setSelectedIndex(0);
        }

        if (cboSubject.getItemCount() > 0) {
            cboSubject.setSelectedIndex(0);
        }

        if (cboTeacher.getItemCount() > 0) {
            cboTeacher.setSelectedIndex(0);
        }

        if (cboDay.getItemCount() > 0) {
            cboDay.setSelectedIndex(0);
        }

        txtStartTime.setText("");
        txtEndTime.setText("");
        txtRoom.setText("");

        tblSchedule.clearSelection();
    }

