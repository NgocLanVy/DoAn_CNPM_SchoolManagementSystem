    private void customizeUI() {

        setTitle("Quản lý giáo viên");
        setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);

        tableModel = new DefaultTableModel(
                new Object[]{
                    "ID",
                    "Mã GV",
                    "Họ tên",
                    "Chuyên môn",
                    "Ngày vào làm"
                }, 0) {

            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tblTeachers.setModel(tableModel);

        cboGender.removeAllItems();
        cboGender.addItem("Nam");
        cboGender.addItem("Nữ");

        tblTeachers.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                onRowSelected();
            }
        });
    }

    private void registerEvents() {

        btnAdd.addActionListener(e -> btnAddActionPerformed(e));

        btnUpdate.addActionListener(e -> btnUpdateActionPerformed(e));

        btnDelete.addActionListener(e -> btnDeleteActionPerformed(e));

        btnClear.addActionListener(e -> btnClearActionPerformed(e));

        btnBack.addActionListener(e -> btnBackActionPerformed(e));
    }

    private void loadTable() {

        tableModel.setRowCount(0);

        for (TeacherProfile t : teacherDAO.getAll()) {

            String hireDate = "";

            if (t.getHireDate() != null) {
                hireDate = sdf.format(t.getHireDate());
            }

            tableModel.addRow(new Object[]{
                t.getId(),
                t.getTeacherCode(),
                t.getFullName(),
                t.getSpecialization(),
                hireDate
            });
        }
    }

    private void onRowSelected() {

        int row = tblTeachers.getSelectedRow();

        if (row < 0) {
            return;
        }

        TeacherProfile teacher = teacherDAO.getAll().get(row);

        selectedId = teacher.getId();
        selectedUserId = teacher.getUserId();

        txtTeacherCode.setText(teacher.getTeacherCode());
        txtFullName.setText(teacher.getFullName());
        txtSpecialization.setText(
                teacher.getSpecialization() == null
                ? ""
                : teacher.getSpecialization()
        );

        if (teacher.getHireDate() != null) {
            txtHireDate.setText(
                    sdf.format(teacher.getHireDate())
            );
        } else {
            txtHireDate.setText("");
        }
    }

