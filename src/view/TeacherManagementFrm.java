    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String fullName = txtFullName.getText().trim();
        String username = txtUsername.getText().trim();
        String password = txtPassword.getText().trim();
        String gender = (String) cboGender.getSelectedItem();
        String teacherCode = txtTeacherCode.getText().trim();
        String specialization = txtSpecialization.getText().trim();
        String hireDateText = txtHireDate.getText().trim();

        if (fullName.isEmpty()
                || username.isEmpty()
                || password.isEmpty()
                || teacherCode.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng nhập đầy đủ thông tin bắt buộc!"
            );

            return;
        }

        Date hireDate = null;

        if (!hireDateText.isEmpty()) {

            try {

                sdf.setLenient(false);

                hireDate = new Date(
                        sdf.parse(hireDateText).getTime()
                );

            } catch (ParseException e) {

                JOptionPane.showMessageDialog(
                        this,
                        "Ngày vào làm phải có dạng dd/MM/yyyy!"
                );

                return;
            }
        }

        boolean result = teacherDAO.insert(
                username,
                password,
                fullName,
                gender,
                teacherCode,
                specialization,
                hireDate
        );

        if (result) {

            JOptionPane.showMessageDialog(
                    this,
                    "Thêm giáo viên thành công!"
            );

            loadTable();
            btnClearActionPerformed(null);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Thêm giáo viên thất bại!\n"
                    + "Username hoặc mã giáo viên có thể đã tồn tại."
            );
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (selectedId < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn giáo viên trong bảng!"
            );

            return;
        }

        String teacherCode = txtTeacherCode.getText().trim();
        String fullName = txtFullName.getText().trim();
        String gender = (String) cboGender.getSelectedItem();
        String specialization = txtSpecialization.getText().trim();
        String hireDateText = txtHireDate.getText().trim();

        if (teacherCode.isEmpty() || fullName.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Mã giáo viên và họ tên không được để trống!"
            );

            return;
        }

        Date hireDate = null;

        if (!hireDateText.isEmpty()) {

            try {

                sdf.setLenient(false);

                hireDate = new Date(
                        sdf.parse(hireDateText).getTime()
                );

            } catch (ParseException e) {

                JOptionPane.showMessageDialog(
                        this,
                        "Ngày vào làm phải có dạng dd/MM/yyyy!"
                );

                return;
            }
        }

        TeacherProfile teacher = new TeacherProfile();

        teacher.setId(selectedId);
        teacher.setUserId(selectedUserId);
        teacher.setTeacherCode(teacherCode);
        teacher.setSpecialization(specialization);
        teacher.setHireDate(hireDate);

        boolean result = teacherDAO.update(
                teacher,
                fullName,
                gender
        );

        if (result) {

            JOptionPane.showMessageDialog(
                    this,
                    "Cập nhật giáo viên thành công!"
            );

            loadTable();
            btnClearActionPerformed(null);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Cập nhật giáo viên thất bại!"
            );
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedId < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn giáo viên trong bảng!"
            );

            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Bạn có chắc muốn xóa giáo viên này?",
                "Xác nhận xóa",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        boolean result = teacherDAO.delete(
                selectedId,
                selectedUserId
        );

        if (result) {

            JOptionPane.showMessageDialog(
                    this,
                    "Xóa giáo viên thành công!"
            );

            loadTable();
            btnClearActionPerformed(null);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Xóa giáo viên thất bại!\n"
                    + "Có thể giáo viên đang được sử dụng ở dữ liệu khác."
            );
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

