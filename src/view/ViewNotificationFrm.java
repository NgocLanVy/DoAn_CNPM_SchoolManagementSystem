    private void customizeUI() {
        tableModel = new DefaultTableModel(
                new Object[]{"ID", "Người gửi", "Tiêu đề", "Ngày gửi", "Trạng thái"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblNotifications.setModel(tableModel);
        tblNotifications.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        // Ẩn cột ID (vẫn giữ dữ liệu, chỉ ẩn khỏi giao diện)
        tblNotifications.getColumnModel().getColumn(0).setMinWidth(0);
        tblNotifications.getColumnModel().getColumn(0).setMaxWidth(0);
        tblNotifications.getColumnModel().getColumn(0).setWidth(0);

        tblNotifications.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                onRowSelected();
            }
        });
    }

    private void loadTable() {
        tableModel.setRowCount(0);
        if (currentUser == null) {
            return;
        }
        currentList = notificationDAO.getByReceiver(currentUser.getId());
        for (Notification n : currentList) {
            String createdDate = n.getCreatedDate() != null ? sdf.format(n.getCreatedDate()) : "";
            tableModel.addRow(new Object[]{
                n.getId(), n.getSenderName(), n.getTitle(), createdDate,
                n.isRead() ? "Đã đọc" : "Chưa đọc"
            });
        }
        txtAreaDetail.setText("");
    }

    private void onRowSelected() {
        int row = tblNotifications.getSelectedRow();
        if (row < 0 || currentList == null || row >= currentList.size()) {
            return;
        }
        Notification n = currentList.get(row);
        txtAreaDetail.setText(n.getContent());

        if (!n.isRead()) {
            notificationDAO.markAsRead(n.getId());
            n.setRead(true);
            tableModel.setValueAt("Đã đọc", row, 4);
        }
    }

