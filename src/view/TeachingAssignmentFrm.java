    private void customizeUI() {

        tableModel = new DefaultTableModel(
                new Object[]{
                    "ID",
                    "Lớp",
                    "Môn học",
                    "Mã môn",
                    "Giáo viên",
                    "Năm học"
                },
                0
        ) {

            @Override
            public boolean isCellEditable(
                    int row,
                    int column
            ) {
                return false;
            }
        };

        tblAssignments.setModel(tableModel);

        tblAssignments.getSelectionModel()
                .addListSelectionListener(
                        e -> onRowSelected()
                );
    }

    private void loadClassCombo() {

        cboClass.removeAllItems();

        for (SchoolClass c : classDAO.getAll()) {
            cboClass.addItem(c);
        }
    }

    private void onRowSelected() {

        int row = tblAssignments.getSelectedRow();

        if (row < 0) {
            return;
        }

        selectedId
                = (int) tableModel.getValueAt(row, 0);

        String className
                = tableModel.getValueAt(row, 1).toString();

        String subjectCode
                = tableModel.getValueAt(row, 3).toString();

        String teacherName
                = tableModel.getValueAt(row, 4).toString();

        String schoolYear
                = tableModel.getValueAt(row, 5).toString();

        txtSchoolYear.setText(schoolYear);

        // Chọn lớp
        for (int i = 0;
                i < cboClass.getItemCount();
                i++) {

            SchoolClass c
                    = cboClass.getItemAt(i);

            if (c.getClassName()
                    .equals(className)) {

                cboClass.setSelectedIndex(i);
                break;
            }
        }

        // Chọn môn
        for (int i = 0;
                i < cboSubject.getItemCount();
                i++) {

            Subject s
                    = cboSubject.getItemAt(i);

            if (s.getSubjectCode()
                    .equals(subjectCode)) {

                cboSubject.setSelectedIndex(i);
                break;
            }
        }

        // Chọn giáo viên
        for (int i = 0;
                i < cboTeacher.getItemCount();
                i++) {

            TeacherProfile t
                    = cboTeacher.getItemAt(i);

            if (t.getFullName() != null
                    && t.getFullName()
                            .equals(teacherName)) {

                cboTeacher.setSelectedIndex(i);
                break;
            }
        }
    }

    private void loadSubjectCombo() {

        cboSubject.removeAllItems();

        for (Subject s : subjectDAO.getAll()) {
            cboSubject.addItem(s);
        }
    }

    private void loadTeacherCombo() {

        cboTeacher.removeAllItems();

        for (TeacherProfile t : teacherDAO.getAll()) {
            cboTeacher.addItem(t);
        }
    }

    private void loadTable() {

        tableModel.setRowCount(0);

        for (TeachingAssignment ta : assignmentDAO.getAll()) {

            tableModel.addRow(
                    new Object[]{
                        ta.getId(),
                        ta.getClassName(),
                        ta.getSubjectName(),
                        ta.getSubjectCode(),
                        ta.getTeacherName(),
                        ta.getSchoolYear()
                    }
            );
        }
    }

