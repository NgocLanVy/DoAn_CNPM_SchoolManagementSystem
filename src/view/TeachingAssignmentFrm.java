    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        SchoolClass c= (SchoolClass) cboClass.getSelectedItem();
        Subject s= (Subject) cboSubject.getSelectedItem();
        TeacherProfile t= (TeacherProfile) cboTeacher.getSelectedItem();
        String schoolYear= txtSchoolYear.getText().trim();

        if (c == null
                || s == null
                || t == null
                || schoolYear.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin!");
            return;
        }

        TeachingAssignment ta = new TeachingAssignment();

        ta.setSchoolClassId(c.getId());
        ta.setSubjectId(s.getId());
        ta.setTeacherProfileId(t.getId());
        ta.setSchoolYear(schoolYear);

        if (assignmentDAO.insert(ta)) {
            JOptionPane.showMessageDialog(this, "Thêm phân công thành công!");
            loadTable();
            clearForm();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Thêm phân công thất bại!"
            );
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (selectedId < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn một phân công!"
            );

            return;
        }

        SchoolClass c
                = (SchoolClass) cboClass.getSelectedItem();

        Subject s
                = (Subject) cboSubject.getSelectedItem();

        TeacherProfile t
                = (TeacherProfile) cboTeacher.getSelectedItem();

        String schoolYear
                = txtSchoolYear.getText().trim();

        if (c == null
                || s == null
                || t == null
                || schoolYear.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng nhập đầy đủ thông tin!"
            );

            return;
        }

        TeachingAssignment ta
                = new TeachingAssignment();

        ta.setId(selectedId);
        ta.setSchoolClassId(c.getId());
        ta.setSubjectId(s.getId());
        ta.setTeacherProfileId(t.getId());
        ta.setSchoolYear(schoolYear);

        if (assignmentDAO.update(ta)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Cập nhật thành công!"
            );

            loadTable();
            clearForm();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Cập nhật thất bại!"
            );
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedId < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn một phân công!"
            );

            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Bạn có chắc muốn xóa phân công này?",
                "Xác nhận xóa",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {

            if (assignmentDAO.delete(selectedId)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Xóa thành công!"
                );

                loadTable();
                clearForm();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Xóa thất bại!"
                );
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

