    private void customizeUI() {
        if (currentUser == null || currentUser.getRoleId() != 2) {
            JOptionPane.showMessageDialog(this, "Chức năng này chỉ dành cho giáo viên!", "Thông báo", JOptionPane.WARNING_MESSAGE);
            this.dispose();
            if (currentUser != null) {
                new MainMenuFrm(currentUser).setVisible(true);
            } else {
                new LoginFrm().setVisible(true);
            }
            return;
        }
        lblTeacherName.setText(currentUser.getFullName());
        classTableModel = new DefaultTableModel(
                new Object[]{
                    "STT", "Lớp", "Môn học", "Mã môn", "Năm học"
                }, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblClasses.setModel(classTableModel);
        tblClasses.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        studentTableModel = new DefaultTableModel(
                new Object[]{
                    "STT", "Mã học sinh", "Họ tên", "Giới tính"
                }, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblStudents.setModel(studentTableModel);
        tblStudents.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }

    private void loadClasses() {
        classTableModel.setRowCount(0);
        studentTableModel.setRowCount(0);
        assignmentList = teachingAssignmentDAO.getByTeacherUserId(currentUser.getId());
        int stt = 1;
        for (TeachingAssignment ta : assignmentList) {
            classTableModel.addRow(new Object[]{
                stt++,
                ta.getClassName(),
                ta.getSubjectName(),
                ta.getSubjectCode(),
                ta.getSchoolYear()
            });
        }
        if (assignmentList.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Bạn chưa được phân công giảng dạy lớp nào.", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
        }
    }

    private void loadStudents(int classId) {
        studentTableModel.setRowCount(0);
        List<StudentProfile> students = studentDAO.getByClass(classId);
        int stt = 1;
        for (StudentProfile sp : students) {
            studentTableModel.addRow(new Object[]{
                stt++,
                sp.getStudentCode(),
                sp.getFullName(),
                sp.getGender()
            });
        }
    }

    private void registerEvents() {
        tblClasses.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                int row = tblClasses.getSelectedRow();
                if (row < 0 || assignmentList == null) {
                    return;
                }
                if (row >= assignmentList.size()) {
                    return;
                }
                TeachingAssignment assignment = assignmentList.get(row);
                loadStudents(assignment.getSchoolClassId());
            }
        });
    }

